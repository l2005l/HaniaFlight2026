#!/bin/sh
# Builds src/vo.js: the cockpit voice warnings as small mp3 clips embedded in the page.
# Needs espeak-ng and ffmpeg (apt-get install espeak-ng ffmpeg). Run from the repo root.
set -e
T=$(mktemp -d)
out=src/vo.js
printf '/* cockpit voice warnings, generated by tools/vo/make_vo.sh (espeak-ng, band-limited like an intercom) */\nconst VO_SRC={\n' > $out
while IFS='|' read -r k txt; do
  [ -z "$k" ] && continue
  espeak-ng -v en-us+f3 -s 165 -p 50 -a 160 -w "$T/$k.wav" "$txt"
  ffmpeg -nostdin -loglevel error -y -i "$T/$k.wav" -af "highpass=f=320,lowpass=f=3400,acompressor=threshold=-18dB:ratio=4,volume=1.6,silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse" -ac 1 -ar 22050 -b:a 32k "$T/$k.mp3"
  printf "  %s:'data:audio/mpeg;base64,%s',\n" "$k" "$(base64 -w0 "$T/$k.mp3")" >> $out
done <<'LIST'
pull|Pull up. Pull up.
bingo|Bingo fuel. Bingo fuel.
fuel|Fuel low.
coll|Warning. Collision. Collision.
msl|Missile. Missile.
fire|Engine fire.
eng|Engine out.
overg|Over G. Over G.
gear|Landing gear.
LIST
printf '};\n' >> $out
rm -rf "$T"
